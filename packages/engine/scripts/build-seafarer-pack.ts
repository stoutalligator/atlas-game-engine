// Builds a Seafarer pack from its plan.
//
//   pnpm --filter @stoutalligator/engine exec tsx scripts/build-seafarer-pack.ts <pack-id> [--review]
//
// Pack ids: shattered-isles (November), frozen-passages (December).
// For each day: generate candidates (deterministic seeds), keep the pinned
// `pick` or the top-ranked one, and write src/games/seafarer/packs/<pack-id>.ts.
// --review also writes the top 6 candidates per day to
// apps/playground/public/seafarer-review-<pack-id>.json for the playground's review page.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { regionSides } from "../src/games/seafarer/expedition.js";
import {
  type Candidate,
  generateCandidate,
  generateCandidates,
} from "../src/games/seafarer/generator.js";
import { FROZEN_PASSAGES_PACK_PLAN } from "../src/games/seafarer/packs/frozen-passages.plan.js";
import type { PackPlan } from "../src/games/seafarer/packs/plan.js";
import { SHATTERED_ISLES_PACK_PLAN } from "../src/games/seafarer/packs/shattered-isles.plan.js";
import { linkVoyages } from "../src/games/seafarer/rules.js";
import type { SeafarerPack, SeafarerPuzzle } from "../src/games/seafarer/types.js";

const PLANS: Record<string, PackPlan> = {
  [SHATTERED_ISLES_PACK_PLAN.id]: SHATTERED_ISLES_PACK_PLAN,
  [FROZEN_PASSAGES_PACK_PLAN.id]: FROZEN_PASSAGES_PACK_PLAN,
};
const plan = PLANS[process.argv.slice(2).find((a) => !a.startsWith("--")) ?? ""];
if (!plan) {
  console.error(`Usage: build-seafarer-pack.ts <${Object.keys(PLANS).join(" | ")}> [--review]`);
  process.exit(1);
}
const PACK_ID = plan.id;
/** The exported constant: "frozen-passages" → FROZEN_PASSAGES. */
const CONST = PACK_ID.toUpperCase().replace(/-/g, "_");
const review = process.argv.includes("--review");
const root = resolve(import.meta.dirname, "..");

const puzzles: SeafarerPuzzle[] = [];
const reviewOut: Array<{
  day: number;
  title: string;
  candidates: Array<Candidate & { seed: string }>;
}> = [];
const usedSeeds = new Set<string>();
const failed: number[] = [];

plan.days.forEach((day, i) => {
  const n = i + 1;
  const prefix = `${PACK_ID}-${String(n).padStart(2, "0")}`;
  const t0 = Date.now();
  let chosen: Candidate | null = null;
  let candidates: Candidate[] = [];
  // Where this region meets yesterday's and tomorrow's on the expedition chart.
  const sides = regionSides(i, plan.days.length);
  const recipe = { ...day.recipe, entrySide: sides.entry, exitSide: sides.exit };
  if (day.pick) {
    chosen = generateCandidate(recipe, day.pick);
    if (!chosen) throw new Error(`Day ${n}: pinned seed ${day.pick} no longer passes its recipe`);
  }
  if (!chosen || review) {
    candidates = generateCandidates(recipe, prefix, day.attempts ?? 600).filter(
      (c) => !usedSeeds.has(c.puzzle.id),
    );
    chosen ??= candidates[0] ?? null;
  }
  if (!chosen) {
    // Keep going, so one run lists every day that needs a looser recipe.
    console.log(`${String(n).padStart(2)} ${day.title.padEnd(22)} NO CANDIDATE PASSED`);
    failed.push(n);
    return;
  }
  usedSeeds.add(chosen.puzzle.id);
  const m = chosen.metrics;
  console.log(
    `${String(n).padStart(2)} ${day.title.padEnd(22)} ${chosen.puzzle.objective.type.padEnd(7)} par ${String(m.par).padStart(2)} prov ${String(chosen.puzzle.provisions).padStart(2)} detour ${m.detour.toFixed(2)} cur+${m.currentGain} shal-${m.shallowCost} greedy+${m.greedyGap} lure+${m.lureGap} exit${m.exitDistance}  [${candidates.length || 1} ok, ${Date.now() - t0}ms] ${chosen.puzzle.id}`,
  );
  puzzles.push({
    ...chosen.puzzle,
    id: `${PACK_ID}-${String(n).padStart(2, "0")}`,
    number: n,
    title: day.title,
    difficulty: day.difficulty,
    ...(day.tip ? { tip: day.tip } : {}),
    meta: { seed: chosen.puzzle.id, metrics: chosen.puzzle.meta?.metrics },
  });
  if (review)
    reviewOut.push({
      day: n,
      title: day.title,
      candidates: candidates.slice(0, 6).map((c) => ({ ...c, seed: c.puzzle.id })),
    });
});

if (failed.length) {
  console.error(`
No chart passed for day(s) ${failed.join(", ")}: loosen those recipes. Nothing written.`);
  process.exit(1);
}

const pack: SeafarerPack = {
  id: PACK_ID,
  title: plan.title,
  description: plan.description,
  theme: plan.theme,
  badgeTiers: plan.badgeTiers,
  // Today departs from where yesterday's voyage ended.
  puzzles: linkVoyages(puzzles, plan.names.ports),
};

const out = resolve(root, `src/games/seafarer/packs/${PACK_ID}.ts`);
const header = [
  `// Generated by scripts/build-seafarer-pack.ts from ${PACK_ID}.plan.ts. Do not edit by`,
  "// hand: change the plan (or pin a reviewed seed with `pick`) and rebuild.",
  'import type { SeafarerPack } from "../types.js";',
  "",
].join("\n");
writeFileSync(
  out,
  `${header}\nexport const ${CONST}: SeafarerPack = ${JSON.stringify(pack, null, 1)};\n`,
);
console.log(`\nWrote ${puzzles.length} challenges → ${out}`);
if (review) {
  const rp = resolve(root, `../../apps/playground/public/seafarer-review-${PACK_ID}.json`);
  writeFileSync(rp, JSON.stringify(reviewOut));
  console.log(`Review candidates → ${rp}`);
}
