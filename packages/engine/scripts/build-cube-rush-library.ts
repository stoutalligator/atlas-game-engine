// Builds src/games/cube-rush/library.ts: generated Cube Rush puzzles that a
// breadth-first solver has verified, each with its par (fewest moves).
//
//   pnpm --filter @stoutalligator/engine build:cube-rush
//
// Puzzles outside the par band for their difficulty (too easy, too hard to
// verify, or unsolvable) are discarded.

import { writeFileSync } from "node:fs";
import { resolve } from "node:path";
import {
  type Difficulty,
  decodePuzzle,
  encodePuzzle,
  generateCubeRush,
  solveCubeRush,
} from "../src/games/cube-rush/logic.ts";

const TARGET = 80;
const BANDS: Record<Difficulty, [number, number]> = {
  easy: [5, 8],
  medium: [8, 12],
  hard: [11, 30],
};

const out: Record<Difficulty, string[]> = { easy: [], medium: [], hard: [] };

for (const difficulty of Object.keys(BANDS) as Difficulty[]) {
  const [lo, hi] = BANDS[difficulty];
  const seen = new Set<string>();
  for (let seed = 0; out[difficulty].length < TARGET && seed < 20_000; seed++) {
    const pz = generateCubeRush(`lib-${seed}`, difficulty);
    const par = solveCubeRush(pz, 2_000_000);
    if (par === null || par < lo || par > hi) continue;
    const code = encodePuzzle(pz, par);
    if (seen.has(code)) continue;
    // Round-trip check.
    if (solveCubeRush(decodePuzzle(code).puzzle, 2_000_000) !== par) throw new Error("round trip");
    seen.add(code);
    out[difficulty].push(code);
    process.stdout.write(
      `${difficulty} ${out[difficulty].length}/${TARGET} (seed ${seed}, par ${par})\n`,
    );
  }
}

const body = (Object.keys(out) as Difficulty[])
  .map((d) => `  ${d}: [\n${out[d].map((c) => `    "${c}",`).join("\n")}\n  ],`)
  .join("\n");

writeFileSync(
  resolve(import.meta.dirname, "../src/games/cube-rush/library.ts"),
  `// Generated by scripts/build-cube-rush-library.ts — do not edit by hand.
// Every entry was solved by breadth-first search; the number after the gate is its par.
import type { Difficulty } from "./logic.js";

export const CUBE_RUSH_LIBRARY: Record<Difficulty, string[]> = {
${body}
};
`,
);
