// The Lantern Sea (January): a night voyage, and the month's new mechanic,
// the tide. Tidal flats (~) are open at high tide and dry at low tide on a
// regular cycle; the tide clock shows the nights ahead. Design notes:
// docs/seafarer.md, "January: The Lantern Sea".
//
// Every month starts gentle (late joiners start at day 1) and gets harder:
//   1–3   Voyages, a refresher, with the base mechanic (glowing shallows) from day 1.
//   4–8   Tides: first open/closed flats, then racing the tide.
//   9–12  Tides with the glowing shallows.
//   13–16 Tides with night currents.
//   17–21 Rounds: nearest-first is a trap, and so is ignoring the tide.
//   22–26 Squall season, on top of the tides.
//   27–30 Charters and the hardest rounds.
//   31    The Lantern Crown: everything at once.

